    fd = d.get("front_doors") or {}
    mcp_targets, unmapped = [], []
    for i, g in enumerate(mcp_groups + [{"name": x["name"], "members": [x["key"].split(":", 1)[1]], "asset": x} for x in singles]):
        server = ((g["asset"]["attrs"].get("mcp") or {}).get("server_name")) or g["name"]
        m = (fd.get("mcp") or {}).get(server)
        if m:
            mcp_targets.append({**g, "server": server, "vip": m["vip"], "front_door": m["name"]})
