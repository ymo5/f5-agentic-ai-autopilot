        def mine_of(r):   # findings of rule r that THIS package addresses (S-007 depends on the contradicted claim)
            return [f for f in by_rule.get(r, []) if catalog.meta(r, f["title"])["package"] == kind]
        addressed = [{"rule": r, "issue": catalog.meta(r)["issue"], "class": catalog.meta(r)["class_label"], "count": len(mine_of(r)),
                      "proven_by": sorted({t for f in mine_of(r) for t in catalog.meta(r, f["title"])["tests"]})} for r in mine]
        other = "security" if kind == "delivery" else "delivery"
