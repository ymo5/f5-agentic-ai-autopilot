"""AI Data Delivery package (integration increment 1, offline): BIG-IP_C virtual servers for the existing AI data services.

    s3_seaweedfs  S3 VIP        -> SeaweedFS  (SigV4 auth stays end-to-end; BIG-IP holds no S3 credentials)
    rag_qdrant    RAG VIP       -> Qdrant
    llm_ollama    Inference VIP -> Ollama

The package is CUMULATIVE like the existing ones: it takes the validated AI Security declaration (delivery + security)
and appends three applications and their shared objects. Every existing object is left byte-identical, so the
rollback is simply the Security-stage declaration. Nothing here talks to BIG-IP; the deployer's policy and the approval
workflow (preview, diff, preflight, window, read-back, validation gate) remain the only way to apply it.

S3 request telemetry: a Statistics_Profile plus an OBSERVE-ONLY iRule (adapted from the Project B lab's s3_irule_query):
it only increments counters. It never responds, redirects, rejects, drops, collects payloads or changes headers, and every
handler is wrapped in catch so a counting error can never affect traffic. Byte counts come from Content-Length headers.
"""
from __future__ import annotations

import copy
import ipaddress
import re

SERVICES = ("s3", "rag", "llm")
APP = {"s3": "s3_seaweedfs", "rag": "rag_qdrant", "llm": "llm_ollama"}
STATS_FIELDS = ["s3_requests", "s3_get", "s3_put", "s3_delete", "s3_head", "s3_list_bucket", "s3_get_object", "s3_put_object",
                "s3_unsigned", "s3_put_bytes", "s3_get_bytes", "s3_resp_2xx", "s3_resp_4xx", "s3_resp_5xx", "s3_large_put"]

# BIG-IP health monitors, matched to what each service returns WITHOUT credentials (verified read-only on 2026-10-18):
#   SeaweedFS GET /            -> 403 <Code>AccessDenied</Code>   (S3 API alive, authentication enforced)
#   Qdrant    GET /readyz      -> 200 "all shards are ready"
#   Ollama    GET /api/version -> 200 {"version":"0.12.6"}
MONITORS = {
    "s3": ("GET / HTTP/1.1\\r\\nHost: {host}\\r\\nConnection: close\\r\\n\\r\\n", "<Code>AccessDenied</Code>"),
    "rag": ("GET /readyz HTTP/1.1\\r\\nHost: {host}\\r\\nConnection: close\\r\\n\\r\\n", "all shards are ready"),
    "llm": ("GET /api/version HTTP/1.1\\r\\nHost: {host}\\r\\nConnection: close\\r\\n\\r\\n", "\"version\""),
}

IRULE_S3_STATS = r"""# AI Data Delivery: S3 request telemetry (OBSERVE ONLY, generated by Autopilot).
# Counts S3 operations on the S3 virtual server into the Statistics profile @@STATS@@.
# Never responds / redirects / rejects / drops / collects payloads / modifies headers; every handler is wrapped in catch.
when HTTP_REQUEST priority 900 {
  if { [catch {
    set s3_m [HTTP::method]
    set s3_p [HTTP::path]
    STATS::incr @@STATS@@ s3_requests 1
    if { ![string match "AWS4-HMAC-SHA256*" [HTTP::header value "Authorization"]] } { STATS::incr @@STATS@@ s3_unsigned 1 }
    set s3_obj [regexp {^/[^/]+/.+} $s3_p]
    switch -- $s3_m {
      "GET" {
        STATS::incr @@STATS@@ s3_get 1
        if { $s3_obj } { STATS::incr @@STATS@@ s3_get_object 1 } else { STATS::incr @@STATS@@ s3_list_bucket 1 }
      }
      "PUT" {
        STATS::incr @@STATS@@ s3_put 1
        if { $s3_obj } { STATS::incr @@STATS@@ s3_put_object 1 }
        set s3_len [HTTP::header value "Content-Length"]
        if { [string is integer -strict $s3_len] && $s3_len > 0 } {
          STATS::incr @@STATS@@ s3_put_bytes $s3_len
          if { $s3_len > 1048576 } { STATS::incr @@STATS@@ s3_large_put 1 }
        }
      }
      "DELETE" { STATS::incr @@STATS@@ s3_delete 1 }
      "HEAD" { STATS::incr @@STATS@@ s3_head 1 }
    }
  } s3_err] } { log local0.notice "ai-data-delivery s3 stats skipped: [string range $s3_err 0 120]" }
}
when HTTP_RESPONSE priority 900 {
  if { [catch {
    set s3_st [HTTP::status]
    if { $s3_st >= 500 } { STATS::incr @@STATS@@ s3_resp_5xx 1 } elseif { $s3_st >= 400 } { STATS::incr @@STATS@@ s3_resp_4xx 1 } elseif { $s3_st >= 200 && $s3_st < 300 } { STATS::incr @@STATS@@ s3_resp_2xx 1 }
    set s3_rl [HTTP::header value "Content-Length"]
    if { [string is integer -strict $s3_rl] && $s3_rl > 0 } { STATS::incr @@STATS@@ s3_get_bytes $s3_rl }
  } s3_err] } { log local0.notice "ai-data-delivery s3 stats skipped: [string range $s3_err 0 120]" }
}"""

FORBIDDEN_IRULE = re.compile(r"\b(HTTP::respond|HTTP::redirect|reject|drop|discard|HTTP::collect|HTTP::header\s+(insert|remove|replace)|"
                             r"HTTP::payload\s+replace|TCP::close|persist)\b")


def irule_s3_stats(tenant: str) -> str:
    return IRULE_S3_STATS.replace("@@STATS@@", f"/{tenant}/Shared/stats_s3")


def check_design(dd: dict, vip_range: str = "10.50.10.96/28", member_range: str = "10.50.20.0/24") -> list[str]:
    """Static checks on the design.data_delivery block (the deployer policy checks the declaration again)."""
    errs, seen = [], set()
    vr, mr = ipaddress.ip_network(vip_range), ipaddress.ip_network(member_range)
    for s in SERVICES:
        c = dd.get(s)
        if not c:
            errs.append(f"data_delivery.{s} missing"); continue
        if ipaddress.ip_address(c["vip"]) not in vr:
            errs.append(f"data_delivery.{s}.vip {c['vip']} outside {vr}")
        if (c["vip"], c["port"]) in seen:
            errs.append(f"data_delivery.{s}: {c['vip']}:{c['port']} already used")
        seen.add((c["vip"], c["port"]))
        if not 1 <= int(c["port"]) <= 65535:
            errs.append(f"data_delivery.{s}.port invalid")
        if not c.get("members"):
            errs.append(f"data_delivery.{s}.members empty")
        for m in c.get("members", []):
            a, _, p = m.rpartition(":")
            if ipaddress.ip_address(a) not in mr or not p.isdigit():
                errs.append(f"data_delivery.{s} member {m} outside {mr} or without port")
        if not re.fullmatch(r"[a-z0-9.-]+", c.get("host", "")):
            errs.append(f"data_delivery.{s}.host must be a DNS name")
    vl = dd.get("vlans")
    if not isinstance(vl, list) or not vl or not all(isinstance(v, str) and re.fullmatch(r"[A-Za-z0-9_.-]+", v) for v in vl):
        errs.append("data_delivery.vlans must list the isolated lab VLAN names the data VIPs may listen on")
    return errs


def extend(security_decl: dict, dd: dict, tenant: str = "AP_AI") -> dict:
    """Security-stage declaration + the three data-delivery applications. Existing objects are not modified."""
    errs = check_design(dd)
    if errs:
        raise ValueError("; ".join(errs))
    decl = copy.deepcopy(security_decl)
    t = decl["declaration"][tenant]
    shared = t["Shared"]
    clash = [k for k in ("mon_s3", "mon_rag", "mon_llm", "stats_s3", "irule_s3_stats") if k in shared] + [APP[s] for s in SERVICES if APP[s] in t]
    if clash:
        raise ValueError(f"objects already present in the base declaration: {clash}")
    ref = lambda o: {"use": f"/{tenant}/Shared/{o}"}
    for s in SERVICES:
        send, recv = MONITORS[s]
        shared[f"mon_{s}"] = {"class": "Monitor", "monitorType": "http", "interval": 5, "timeout": 16,
                              "send": send.format(host=dd[s]["host"]), "receive": recv}
    shared["stats_s3"] = {"class": "Statistics_Profile", **{f"field{i + 1}": f for i, f in enumerate(STATS_FIELDS)}}
    shared["irule_s3_stats"] = {"class": "iRule", "iRule": irule_s3_stats(tenant)}
    for s in SERVICES:
        c = dd[s]
        # allowVlans: the HTTP data VIPs listen ONLY on the isolated lab VLANs (AS3 default would be all VLANs)
        svc = {"class": "Service_HTTP", "virtualAddresses": [c["vip"]], "virtualPort": int(c["port"]), "pool": "pool", "snat": "auto",
               "profileHTTP": ref("http_ai"), "profileTCP": ref("tcp_ai"), "iRules": [], "persistenceMethods": [],
               "allowVlans": [{"bigip": f"/Common/{v}"} for v in dd["vlans"]]}
        if s == "s3":
            svc["iRules"] = [ref("irule_s3_stats")]
            svc["profileStatistics"] = ref("stats_s3")
        t[APP[s]] = {"class": "Application", "service": svc,
                     "pool": {"class": "Pool", "loadBalancingMode": "least-connections-member", "monitors": [ref(f"mon_{s}")],
                              "members": [{"servicePort": int(m.rpartition(":")[2]), "serverAddresses": [m.rpartition(":")[0]]}
                                          for m in c["members"]]}}
    decl["declaration"]["id"] = re.sub(r"-(security|delivery)$", "", decl["declaration"].get("id", "autopilot")) + "-data"
    return decl


def added_objects(base: dict, new: dict, tenant: str = "AP_AI") -> dict:
    """What the package adds, and proof that nothing pre-existing changed (used by the change artifact and the tests)."""
    b, n = base["declaration"][tenant], new["declaration"][tenant]
    changed = [k for k in b if k != "Shared" and b[k] != n.get(k)] + [f"Shared/{k}" for k in b["Shared"] if b["Shared"][k] != n["Shared"].get(k)]
    return {"applications": sorted(k for k in n if k not in b and k != "class"),
            "shared_objects": sorted(k for k in n["Shared"] if k not in b["Shared"]),
            "modified_existing": sorted(changed)}


def summary(decl: dict, tenant: str = "AP_AI") -> list[dict]:
    """Architecture rows for the data applications (Service_HTTP has no serverTLS, unlike the MCP/A2A services)."""
    out = []
    for s in SERVICES:
        body = decl["declaration"][tenant].get(APP[s])
        if not body:
            continue
        sv, pl = body["service"], body["pool"]
        out.append({"application": APP[s], "virtual_server": f"{sv['virtualAddresses'][0]}:{sv['virtualPort']}", "tls": "none (HTTP)",
                    "irules": [x["use"].split("/")[-1] for x in sv["iRules"]], "statistics_profile": "stats_s3" if "profileStatistics" in sv else None,
                    "persistence": False, "snat": sv["snat"], "vlans": [v["bigip"] for v in sv.get("allowVlans", [])],
                    "pool_members": [f"{m['serverAddresses'][0]}:{m['servicePort']}" for m in pl["members"]],
                    "monitor": pl["monitors"][0]["use"].split("/")[-1], "lb_mode": pl["loadBalancingMode"]})
    return out
