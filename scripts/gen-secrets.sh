#!/usr/bin/env bash
# Generate the Autopilot web/deployer shared secrets for a NEW installation.
#   scripts/gen-secrets.sh [secrets-dir]      (default: $APLAB_SECRETS or /opt/aplab/secrets)
# Writes <dir>/autopilot.env and <dir>/deployer/deployer_token with mode 0600. Never prints a secret value and never
# overwrites existing files (delete them deliberately to rotate). Deployer device credentials are NOT generated here:
# see docs/CONFIGURATION.md ("Deployer credential files").
set -euo pipefail
umask 077
DIR="${1:-${APLAB_SECRETS:-/opt/aplab/secrets}}"
command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 2; }
mkdir -p "$DIR/deployer"
chmod 700 "$DIR" "$DIR/deployer"
ENV="$DIR/autopilot.env"; TOK="$DIR/deployer/deployer_token"
if [ -e "$ENV" ] || [ -e "$TOK" ]; then
  echo "refusing to overwrite existing secrets in $DIR (autopilot.env / deployer/deployer_token)" >&2; exit 3
fi
SESSION="$(openssl rand -hex 32)"; DTOKEN="$(openssl rand -hex 32)"
{
  echo "# generated by scripts/gen-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) — keep private"
  echo "AUTOPILOT_SESSION_SECRET=$SESSION"
  echo "AUTOPILOT_DEPLOYER_TOKEN=$DTOKEN"
  echo "AUTOPILOT_OPERATOR_TOKEN_SHA256="
} > "$ENV"
printf '%s\n' "$DTOKEN" > "$TOK"
unset SESSION DTOKEN
echo "wrote $ENV and $TOK (mode 0600). Values were not displayed."
echo "If the containers run as uid 10001/10002, give them read access, e.g.: chgrp 10010 $ENV $TOK && chmod 640 $ENV $TOK"
